class PifStage extends Stage {
  constructor(scope: Construct, id: string, props: PifStageProps) {
    super(scope, id, props);
    const { config } = props;
    const core = new CoreStack(this, 'Core', { config, stackName: `pif-${config.stage}-core` });
    const data = new DataStack(this, 'Data', { config, key: core.key, stackName: `pif-${config.stage}-data` });
    const api = new ApiStack(this, 'Api', {
      config,
      stackName: `pif-${config.stage}-api`,
      key: core.key,
      pepper: core.pepper,
      anthropicKey: core.anthropicKey,
      geminiKey: core.geminiKey,
      ssmPrefix: core.ssmPrefix,
      apps: data.apps,
      verdicts: data.verdicts,
      stats: data.stats,
      evalRuns: data.evalRuns,
      evalBucket: data.evalBucket,
    });
    const evalStack = new EvalStack(this, 'Eval', {
      config,
      stackName: `pif-${config.stage}-eval`,
      key: core.key,
      orchestrator: api.orchestrator,
      classifierAliasArn: api.classifierAliasArn,
      evalRuns: data.evalRuns,
      evalBucket: data.evalBucket,
    });
    const obs = new ObservabilityStack(this, 'Observability', {
      config,
      stackName: `pif-${config.stage}-observability`,
      topic: core.alarmTopic,
      dataApi: api.dataApi,
    });
    for (const stack of [core, data, api, evalStack, obs]) {
      NagSuppressions.addStackSuppressions(stack, SUPPRESSIONS);
      Tags.of(stack).add('project', 'pif');
      Tags.of(stack).add('env', config.stage);
    }
  }
}

const app = new App();
const env = { account: process.env.CDK_DEFAULT_ACCOUNT, region: process.env.PIF_REGION ?? 'us-east-1' };
new PifStage(app, 'Dev', { env, config: CONFIGS.dev });
new PifStage(app, 'Prod', { env, config: CONFIGS.prod });
Aspects.of(app).add(new AwsSolutionsChecks({ verbose: true }));
